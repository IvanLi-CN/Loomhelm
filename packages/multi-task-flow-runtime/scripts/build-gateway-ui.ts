import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Check, Copy, TriangleAlert } from "lucide";

// Commit the compiled subset so the Gateway needs neither dev dependencies nor Worker assets.
const root = join(import.meta.dir, "..");
const temporary = mkdtempSync(join(tmpdir(), "mtf-gateway-ui-"));
try {
  const output = join(temporary, "gateway.css");
  const result = Bun.spawnSync(
    [
      join(root, "node_modules/.bin/tailwindcss"),
      "-i",
      "web/gateway-ui.css",
      "-o",
      output,
      "--minify",
    ],
    { cwd: root, stdout: "inherit", stderr: "inherit" },
  );
  if (result.exitCode !== 0) throw new Error("Gateway UI compilation failed");
  const icon = (name: string, nodes: typeof TriangleAlert) =>
    `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="lucide lucide-${name}">${nodes
      .map(
        ([tag, attributes]) =>
          `<${tag} ${Object.entries(attributes)
            .map(([key, value]) => `${key}="${value}"`)
            .join(" ")}/>`,
      )
      .join("")}</svg>`;
  const generated = `// Generated by scripts/build-gateway-ui.ts from the shared Viewer theme, DaisyUI and Lucide.\nexport const gatewayUiCss = ${JSON.stringify(readFileSync(output, "utf8").trim())};\nexport const gatewayWarningIcon = ${JSON.stringify(icon("triangle-alert", TriangleAlert))};\nexport const gatewayCopyIcon = ${JSON.stringify(icon("copy", Copy))};\nexport const gatewayCopiedIcon = ${JSON.stringify(icon("check", Check))};\n`;
  const destination = join(root, "lib/gateway-ui.generated.ts");
  const formatted = Bun.spawnSync(
    [
      join(root, "node_modules/.bin/biome"),
      "format",
      "--stdin-file-path=lib/gateway-ui.generated.ts",
    ],
    { cwd: root, stdin: Buffer.from(generated) },
  );
  if (formatted.exitCode !== 0) throw new Error("Gateway UI formatting failed");
  const contents = formatted.stdout.toString();
  if (process.argv.includes("--check")) {
    if (readFileSync(destination, "utf8") !== contents)
      throw new Error("Gateway UI is stale; run bun run build:gateway-ui");
  } else writeFileSync(destination, contents);
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
